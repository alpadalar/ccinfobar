import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { parseArgs } from '../../src/cli/args.js';
import type { PromptIo } from '../../src/commands/io.js';
import { runImportCommand } from '../../src/commands/manage.js';
import {
  ccStatuslinePath,
  importCcStatusline,
  parseCcStatuslineHeader,
  TARGETS,
} from '../../src/importers/cc-statusline.js';
import { detectTool, importFrom, sniffTool } from '../../src/importers/index.js';
import { makeCtx } from '../../src/importers/registry.js';
import { ALL_WIDGETS } from '../../src/widgets/index.js';
import { withLang } from '../helpers.js';

const FIXTURES = path.join(__dirname, '../fixtures/import');
const FILE = path.join(FIXTURES, 'cc-statusline.sh');
const text = () => fs.readFileSync(FILE, 'utf8');

type R = ReturnType<typeof importCcStatusline>;
const types = (r: R) => r.config.lines!.map((l) => l.map((i) => i.type));
const item = (r: R, type: string) => r.config.lines!.flat().find((i) => i.type === type);
const texts = (r: R) => r.notes.map((n) => n.text);
const header = (theme: string, colors: string, features: string) =>
  `#!/bin/bash\n# Generated by cc-statusline v1.4.0\n# Theme: ${theme} | Colors: ${colors} | Features: ${features}\n`;
const from = (theme: string, colors: string, features: string) =>
  importCcStatusline(parseCcStatuslineHeader(header(theme, colors, features))!);

const ALL = ['directory', 'git', 'model', 'context', 'usage', 'tokens', 'burnrate', 'session'];
const HEADER_ONLY =
  'only the cc-statusline (chongdashu) script header (theme, colors and features) was read; changes made below it are not imported';

describe('parseCcStatuslineHeader', () => {
  it('reads theme, colors and features from the fixture', () => {
    expect(parseCcStatuslineHeader(text())).toEqual({ theme: 'detailed', colors: true, features: ALL });
  });

  it('needs the marker in the first 10 lines and a Theme line after it', () => {
    const late = `${'#\n'.repeat(11)}${header('detailed', 'true', 'git').slice('#!/bin/bash\n'.length)}`;
    expect(late.split('\n')[11]).toMatch(/^# Generated by cc-statusline/);
    expect(parseCcStatuslineHeader(late)).toBeNull();
    expect(parseCcStatuslineHeader('#!/bin/bash\n# Generated by cc-statusline v1.4.0\necho hi\n')).toBeNull();
    expect(parseCcStatuslineHeader('# Theme: detailed | Colors: true | Features: git\n')).toBeNull();
    expect(parseCcStatuslineHeader('')).toBeNull();
  });

  it('reads CRLF scripts and Colors: false', () => {
    const r = parseCcStatuslineHeader(header('compact', 'false', 'git, model').replace(/\n/g, '\r\n'));
    expect(r).toEqual({ theme: 'compact', colors: false, features: ['git', 'model'] });
  });
});

describe('importCcStatusline', () => {
  it('maps every feature to the fixed three lines', () => {
    const r = importCcStatusline(parseCcStatuslineHeader(text())!);
    expect(r.source).toBe('cc-statusline');
    expect(types(r)).toEqual([
      ['cwd', 'git-branch', 'model', 'claude-version', 'output-style'],
      ['context-percentage', 'context-bar', 'five-hour-reset', 'five-hour-usage'],
      ['session-cost', 'cost-rate', 'tokens-total', 'output-speed'],
    ]);
    expect(r.config).toMatchObject({ theme: 'classic', style: 'text', separator: '  ', icons: 'emoji' });
    expect(r.config.colorLevel).toBeUndefined();
    expect(item(r, 'cwd')!.options).toEqual({ style: 'tilde' });
    expect(item(r, 'context-percentage')!.options).toEqual({ mode: 'remaining' });
    expect(item(r, 'context-bar')!.options).toEqual({ showPercent: false });
    expect(item(r, 'five-hour-usage')!.options).toEqual({ display: 'bar' });
    expect(item(r, 'model')!.id).toBe('cc-statusline-model');
    expect(r.notes).toEqual([
      { kind: 'info', text: HEADER_ONLY },
      {
        kind: 'approx',
        text: 'cc-statusline (chongdashu) "context" is approximated by the context-bar widget',
      },
      {
        kind: 'approx',
        text: 'cc-statusline (chongdashu) "session" is approximated by the five-hour-reset widget',
      },
      {
        kind: 'approx',
        text: 'cc-statusline (chongdashu) "burnrate" is approximated by the output-speed widget',
      },
    ]);
  });

  it('leaves out what was not picked', () => {
    const r = from('detailed', 'true', 'directory, model, tokens');
    expect(types(r)).toEqual([['cwd', 'model', 'claude-version', 'output-style'], ['tokens-total']]);
    expect(texts(r)).toEqual([HEADER_ONLY]);
    // burn rate shows only next to the cost or the tokens
    expect(types(from('detailed', 'true', 'burnrate'))).toEqual([['claude-version', 'output-style']]);
    expect(types(from('detailed', 'true', 'usage, burnrate'))[1]).toEqual(['session-cost', 'cost-rate']);
  });

  it('turns colors off and approximates the other themes', () => {
    expect(from('detailed', 'false', 'git').config.colorLevel).toBe(0);
    const minimal = from('minimal', 'true', 'session');
    expect(item(minimal, 'five-hour-usage')!.options).toBeUndefined();
    expect(minimal.config.theme).toBe('classic');
    expect(texts(minimal)).toContain(
      'cc-statusline (chongdashu) theme "minimal" is approximated by the classic theme',
    );
    expect(texts(from('compact', 'true', 'git'))).toContain(
      'cc-statusline (chongdashu) theme "compact" is approximated by the classic theme',
    );
    expect(texts(from('neon', 'true', 'git'))).toContain(
      'cc-statusline (chongdashu) theme "neon" has no ccinfobar equivalent, used the classic theme',
    );
  });

  it('drops unknown and prototype feature names', () => {
    const r = from('detailed', 'true', 'git, weather, __proto__, constructor, weather');
    expect(types(r)).toEqual([['git-branch', 'claude-version', 'output-style']]);
    expect(texts(r).slice(1)).toEqual([
      'cc-statusline (chongdashu) widget "weather" has no ccinfobar equivalent and was skipped',
      'cc-statusline (chongdashu) widget "__proto__" has no ccinfobar equivalent and was skipped',
      'cc-statusline (chongdashu) widget "constructor" has no ccinfobar equivalent and was skipped',
    ]);
  });

  it('lists only existing widgets as targets', () => {
    const known = new Set(ALL_WIDGETS.map((w) => w.type));
    for (const type of TARGETS) expect(known.has(type), type).toBe(true);
  });

  it('writes its notes in Turkish', () => {
    withLang('tr', () => {
      expect(texts(from('compact', 'true', 'git'))).toEqual([
        'cc-statusline (chongdashu) betiğinin yalnızca başlığı (tema, renkler ve özellikler) okundu; altındaki değişiklikler içe aktarılmadı',
        'cc-statusline (chongdashu) teması "compact", classic temasıyla yaklaşık olarak gösteriliyor',
      ]);
    });
  });
});

describe('cc-statusline importer', () => {
  let dir: string;
  let home: string;
  let cwd: string;
  let env: NodeJS.ProcessEnv;

  beforeEach(() => {
    dir = fs.realpathSync.native(fs.mkdtempSync(path.join(os.tmpdir(), 'ccib-ccsl-')));
    home = path.join(dir, 'home');
    cwd = path.join(dir, 'project');
    fs.mkdirSync(path.join(home, '.claude'), { recursive: true });
    fs.mkdirSync(path.join(cwd, '.claude'), { recursive: true });
    env = { HOME: home, USERPROFILE: home };
  });

  afterEach(() => {
    process.exitCode = undefined;
    fs.rmSync(dir, { recursive: true, force: true });
  });

  const homeScript = () => path.join(home, '.claude', 'statusline.sh');
  const cwdScript = () => path.join(cwd, '.claude', 'statusline.sh');
  const where = (command: string) => ccStatuslinePath(makeCtx({ command, env, cwd }));

  it('finds the script named by the command, relative ones against cwd', () => {
    expect(where('bash ~/.claude/statusline.sh')).toBe(homeScript());
    expect(where('~/.claude/statusline.sh')).toBe(homeScript());
    expect(where('bash "$HOME/.claude/statusline.sh"')).toBe(homeScript());
    expect(where('bash .claude/statusline.sh')).toBe(cwdScript());
    const abs = path.join(dir, 'tools', 'statusline.sh');
    expect(where(`bash "${abs}"`)).toBe(abs);
  });

  it('falls back to ~/.claude/statusline.sh when it exists, else <cwd>/.claude/statusline.sh', () => {
    expect(where('')).toBe(cwdScript());
    fs.copyFileSync(FILE, homeScript());
    expect(where('')).toBe(homeScript());
    expect(where('node other.js')).toBe(homeScript());
  });

  it('imports the script from the command, never runs it and leaves it unchanged', () => {
    fs.copyFileSync(FILE, homeScript());
    const before = fs.readFileSync(homeScript());
    const r = importFrom('cc-statusline', { command: 'bash ~/.claude/statusline.sh', env, cwd });
    expect(r.file).toBe(homeScript());
    expect(r.config.lines!.length).toBe(3);
    expect(fs.readFileSync(homeScript()).equals(before)).toBe(true);
  });

  it('reports a script without the marker and a missing script', async () => {
    fs.writeFileSync(homeScript(), '#!/bin/bash\necho "my own line"\n');
    const shown = path.join('~', '.claude', 'statusline.sh');
    expect(() => importFrom('cc-statusline', { command: 'bash ~/.claude/statusline.sh', env, cwd })).toThrow(
      `${shown} is not a script generated by cc-statusline`,
    );
    expect(() => importFrom('cc-statusline', { command: 'bash .claude/statusline.sh', env, cwd })).toThrow(
      /no cc-statusline \(chongdashu\) config found/,
    );
    const lines: string[] = [];
    const io: PromptIo = {
      tty: false,
      ask: async (_q, fallback) => fallback,
      log: (l) => lines.push(l),
      error: (l) => lines.push(l),
      columns: 100,
    };
    const cfgFile = path.join(dir, 'out', 'config.json');
    await runImportCommand(parseArgs(['import', 'cc-statusline', '--file', homeScript()]), cfgFile, io);
    expect(process.exitCode).toBe(1);
    expect(lines.join('\n')).toContain('is not a script generated by cc-statusline');
    expect(fs.existsSync(cfgFile)).toBe(false);
  });

  it('is found by its header sniff, not by the generic command', () => {
    const command = 'bash ~/.claude/statusline.sh';
    expect(detectTool(command)?.tool).toBe('unknown');
    expect(sniffTool(command, { env, cwd })).toBeNull();
    fs.copyFileSync(FILE, homeScript());
    expect(sniffTool(command, { env, cwd })).toEqual({
      tool: 'cc-statusline',
      name: 'cc-statusline (chongdashu)',
      importable: true,
      command,
    });
    // only the command's own script is sniffed
    expect(sniffTool('node ~/my-line.js', { env, cwd })).toBeNull();
    fs.writeFileSync(homeScript(), '#!/bin/bash\necho hi\n');
    expect(sniffTool(command, { env, cwd })).toBeNull();
  });

  it('keeps the fixture a plain, non-executable header', () => {
    if (process.platform !== 'win32') expect(fs.statSync(FILE).mode & 0o111).toBe(0);
    for (const line of text()
      .split('\n')
      .filter((l) => l)) {
      expect(line, line).toMatch(/^(?:#|echo ")/);
    }
  });
});
