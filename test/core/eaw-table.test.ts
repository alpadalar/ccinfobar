import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { AMBIGUOUS, JOIN, UNICODE_VERSION, WIDE, ZERO } from '../../src/core/eaw-table.js';

const inRanges = (t: readonly number[], cp: number) => {
  for (let i = 0; i < t.length; i += 2) if (cp >= t[i]! && cp <= t[i + 1]!) return true;
  return false;
};

const TABLES = { WIDE, AMBIGUOUS, ZERO, JOIN };

describe('eaw-table', () => {
  for (const [name, t] of Object.entries(TABLES)) {
    it(`${name} is sorted, even and non-overlapping`, () => {
      expect(t.length).toBeGreaterThan(0);
      expect(t.length % 2).toBe(0);
      for (let i = 0; i < t.length; i += 2) {
        expect(t[i]!).toBeLessThanOrEqual(t[i + 1]!);
        if (i > 0) expect(t[i]!).toBeGreaterThan(t[i - 1]!);
      }
    });
  }

  it('pins Unicode 16.0.0 and carries the generated header', () => {
    expect(UNICODE_VERSION).toBe('16.0.0');
    const file = path.resolve(__dirname, '../../src/core/eaw-table.ts');
    expect(fs.readFileSync(file, 'utf8').split('\n')[0]).toBe(
      '// Generated by scripts/gen-eaw.mjs from Unicode 16.0.0 data. Do not edit.',
    );
  });

  it('classifies wide code points', () => {
    for (const cp of [0x4e00, 0xac00, 0xff01, 0x1f600, 0x2e80]) {
      expect(inRanges(WIDE, cp), cp.toString(16)).toBe(true);
    }
    for (const cp of [0x41, 0x2500, 0x2588, 0x2800, 0xe0b0]) {
      expect(inRanges(WIDE, cp), cp.toString(16)).toBe(false);
    }
  });

  it('classifies ambiguous code points', () => {
    for (const cp of [0xe9, 0xb7, 0x2502, 0x2588, 0x25cf, 0x2026, 0xe000]) {
      expect(inRanges(AMBIGUOUS, cp), cp.toString(16)).toBe(true);
    }
    for (const cp of [0x41, 0x2800]) expect(inRanges(AMBIGUOUS, cp), cp.toString(16)).toBe(false);
  });

  it('classifies zero-width code points', () => {
    for (const cp of [0x301, 0x200b, 0xfe0f, 0x1160]) expect(inRanges(ZERO, cp), cp.toString(16)).toBe(true);
    expect(inRanges(ZERO, 0x41)).toBe(false);
  });

  it('classifies joining code points but not LV syllables', () => {
    for (const cp of [0x200d, 0xfe0f, 0x20e3, 0x1f3fb, 0x1f1e6, 0x1100]) {
      expect(inRanges(JOIN, cp), cp.toString(16)).toBe(true);
    }
    expect(inRanges(JOIN, 0xac00)).toBe(false);
  });
});
