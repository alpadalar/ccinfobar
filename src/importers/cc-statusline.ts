import '../core/i18n/lazy.js';
import path from 'node:path';
import { t } from '../core/i18n/index.js';
import { sanitizeText } from '../core/sanitize.js';
import type { Config, OptionValue, WidgetItem } from '../core/types.js';
import type { ImportNote, ImportResult } from './index.js';
import { isFile, readSource, SourceTooLargeError, shownFile } from './io.js';
import type { ImportCtx, ImporterDef } from './registry.js';

const TOOL = 'cc-statusline';
const NAME = 'cc-statusline (chongdashu)';
const MARKER = /^#\s*Generated by cc-statusline\b/;
const HEADER = /^#\s*Theme:\s*(\w+)\s*\|\s*Colors:\s*(true|false)\s*\|\s*Features:(.*)$/i;
const HEAD_LINES = 10;

export const TARGETS: readonly string[] = [
  'cwd',
  'git-branch',
  'model',
  'claude-version',
  'output-style',
  'context-percentage',
  'context-bar',
  'five-hour-reset',
  'five-hour-usage',
  'session-cost',
  'cost-rate',
  'tokens-total',
  'output-speed',
];

const FEATURES = new Set(['directory', 'git', 'model', 'context', 'usage', 'tokens', 'burnrate', 'session']);

export interface CcStatuslineHeader {
  theme: string;
  colors: boolean;
  features: string[];
}

// only the comment header is read, the script is never run
export function parseCcStatuslineHeader(text: string): CcStatuslineHeader | null {
  const lines = text.split(/\r?\n/);
  const at = lines.slice(0, HEAD_LINES).findIndex((l) => MARKER.test(l));
  if (at < 0) return null;
  for (const line of lines.slice(at + 1, at + 1 + HEAD_LINES)) {
    const m = HEADER.exec(line);
    if (!m) continue;
    const features = m[3]!
      .split(',')
      .map((f) => f.trim())
      .filter((f) => f);
    return { theme: m[1]!, colors: m[2]!.toLowerCase() === 'true', features };
  }
  return null;
}

type Types = [string, Record<string, OptionValue>?][];

export function importCcStatusline(header: CcStatuslineHeader): ImportResult {
  const notes: ImportNote[] = [{ kind: 'info', text: t('import.note.headerOnly', { tool: TOOL }) }];
  const on = new Set(header.features.filter((f) => FEATURES.has(f)));
  const approx = (name: string, widget: string) =>
    notes.push({ kind: 'approx', text: t('import.note.hudApprox', { tool: TOOL, name, widget }) });

  const theme = header.theme.toLowerCase();
  if (theme === 'minimal' || theme === 'compact') {
    notes.push({
      kind: 'approx',
      text: t('import.note.themeApprox', { tool: TOOL, name: theme, theme: 'classic' }),
    });
  } else if (theme !== 'detailed') {
    notes.push({
      kind: 'approx',
      text: t('import.note.themeMissing', { tool: TOOL, name: sanitizeText(header.theme), theme: 'classic' }),
    });
  }

  const first: Types = [
    ...(on.has('directory') ? ([['cwd', { style: 'tilde' }]] as Types) : []),
    ...(on.has('git') ? ([['git-branch']] as Types) : []),
    ...(on.has('model') ? ([['model']] as Types) : []),
    ['claude-version'],
    ['output-style'],
  ];
  const second: Types = [];
  if (on.has('context')) {
    second.push(['context-percentage', { mode: 'remaining' }], ['context-bar', { showPercent: false }]);
    // its bar fills with the remaining share
    approx('context', 'context-bar');
  }
  if (on.has('session')) {
    // minimal drops the session bar
    second.push(
      ['five-hour-reset'],
      theme === 'minimal' ? ['five-hour-usage'] : ['five-hour-usage', { display: 'bar' }],
    );
    approx('session', 'five-hour-reset');
  }
  const third: Types = [];
  if (on.has('usage')) {
    third.push(['session-cost']);
    if (on.has('burnrate')) third.push(['cost-rate']);
  }
  if (on.has('tokens')) {
    third.push(['tokens-total']);
    if (on.has('burnrate')) {
      third.push(['output-speed']);
      approx('burnrate', 'output-speed');
    }
  }
  const unknown = [...new Set(header.features.filter((f) => !FEATURES.has(f)))];
  for (const name of unknown) {
    notes.push({
      kind: 'drop',
      text: t('import.note.noEquivalent', { tool: TOOL, name: sanitizeText(name) }),
    });
  }

  const used = new Set<string>();
  const lines: WidgetItem[][] = [first, second, third]
    .filter((l) => l.length > 0)
    .map((l) =>
      l.map(([type, options]) => {
        let id = `${TOOL}-${type}`;
        for (let n = 2; used.has(id); n++) id = `${TOOL}-${type}-${n}`;
        used.add(id);
        return { id, type, ...(options ? { options } : {}) };
      }),
    );
  const config: Partial<Config> = {
    lines,
    theme: 'classic',
    style: 'text',
    separator: '  ',
    icons: 'emoji',
    ...(header.colors ? {} : { colorLevel: 0 as const }),
  };
  return { config, notes, source: 'cc-statusline' };
}

// the script named by the status line command
export function commandScript(ctx: ImportCtx): string | null {
  const token = ctx.args.find((a) => /statusline\.sh$/i.test(a));
  if (!token) return null;
  const home = /^(?:~|\$HOME|\$\{HOME\})(?=$|[\\/])/;
  const expanded = home.test(token) ? path.join(ctx.home, token.replace(home, '')) : token;
  // relative, as the Windows install writes it
  return path.resolve(ctx.cwd, expanded);
}

export function ccStatuslinePath(ctx: ImportCtx): string {
  const own = commandScript(ctx);
  if (own) return own;
  const home = path.join(ctx.home, '.claude', 'statusline.sh');
  return isFile(home) ? home : path.join(ctx.cwd, '.claude', 'statusline.sh');
}

function loadScript(file: string | null, ctx: ImportCtx): ImportResult {
  if (!file) throw new Error(t('import.notFound', { tool: NAME, file: '~/.claude/statusline.sh' }));
  const shown = shownFile(file, ctx.home);
  let text: string;
  try {
    text = readSource(file);
  } catch (err) {
    if (err instanceof SourceTooLargeError) throw err;
    throw new Error(t('import.cannotReadTool', { tool: TOOL, file: shown }));
  }
  const header = parseCcStatuslineHeader(text);
  if (!header) throw new Error(t('import.notScript', { file: shown }));
  return { ...importCcStatusline(header), file };
}

export const ccStatuslineImporter: ImporterDef = {
  source: 'cc-statusline',
  name: NAME,
  repo: 'chongdashu/cc-statusline',
  shown: '~/.claude/statusline.sh',
  hasDefault: false,
  sniff: { file: commandScript, marker: /Generated by cc-statusline/ },
  discover: ccStatuslinePath,
  load: loadScript,
};
