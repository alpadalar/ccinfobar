// Runs by hand: regenerates src/core/eaw-table.ts from pinned Unicode data (`--from <dir>` reads local copies).
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UNICODE = '16.0.0';
const BASE = `https://www.unicode.org/Public/${UNICODE}/ucd`;
const FILES = {
  eaw: {
    url: `${BASE}/EastAsianWidth.txt`,
    sha256: '43adc76c0686a42cb370764eb8cfe2b2a45b10b855e5572a2db4a0eecce15d5b',
  },
  emoji: {
    url: `${BASE}/emoji/emoji-data.txt`,
    sha256: 'f1365a5173eee18e1f98b240cdc492e84a25f1ce7e0c9d1094eb29c41a22696a',
  },
  gc: {
    url: `${BASE}/extracted/DerivedGeneralCategory.txt`,
    sha256: '7676ab755a41ef82108460238569e60ad65c191ddafe61b36c6765ec1353f293',
  },
  gcb: {
    url: `${BASE}/auxiliary/GraphemeBreakProperty.txt`,
    sha256: 'c29360bd6f7132811d701d29069541e827eb44bfc4c8fbde8c370d6982689dc1',
  },
};

const args = process.argv.slice(2);
const fromIdx = args.indexOf('--from');
const from = fromIdx >= 0 ? args[fromIdx + 1] : undefined;
if (fromIdx >= 0 && !from) fail('--from needs a directory');
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out = path.join(root, 'src', 'core', 'eaw-table.ts');

function fail(msg) {
  console.error(`gen-eaw: ${msg}`);
  process.exit(1);
}

async function load(url) {
  const name = url.slice(url.lastIndexOf('/') + 1);
  if (from) {
    try {
      return { name, buf: fs.readFileSync(path.join(path.resolve(from), name)) };
    } catch (e) {
      fail(`cannot read ${name}: ${e.message}`);
    }
  }
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(60_000) });
    if (!res.ok) fail(`${url}: HTTP ${res.status}`);
    return { name, buf: Buffer.from(await res.arrayBuffer()) };
  } catch (e) {
    fail(`${url}: ${e.message}`);
  }
}

const text = {};
for (const [key, { url, sha256 }] of Object.entries(FILES)) {
  const { name, buf } = await load(url);
  if (createHash('sha256').update(buf).digest('hex') !== sha256) fail(`sha256 mismatch for ${name}`);
  text[key] = buf.toString('utf8');
}

// `code[..code] ; value # comment`
function parse(src, want) {
  const ranges = [];
  for (const raw of src.split('\n')) {
    const line = raw.replace(/#.*/, '').trim();
    if (!line) continue;
    const m = /^([0-9A-Fa-f]{4,6})(?:\.\.([0-9A-Fa-f]{4,6}))?\s*;\s*([A-Za-z_]+)\s*$/.exec(line);
    if (!m) fail(`bad line: ${raw}`);
    if (!want.has(m[3])) continue;
    const a = Number.parseInt(m[1], 16);
    ranges.push([a, m[2] ? Number.parseInt(m[2], 16) : a]);
  }
  return ranges;
}

function merge(ranges) {
  const sorted = [...ranges].sort((x, y) => x[0] - y[0]);
  const res = [];
  for (const [a, b] of sorted) {
    const last = res[res.length - 1];
    if (last && a <= last[1] + 1) last[1] = Math.max(last[1], b);
    else res.push([a, b]);
  }
  return res;
}

const has = (t, cp) => t.some(([a, b]) => cp >= a && cp <= b);

const tables = {
  WIDE: merge(parse(text.eaw, new Set(['W', 'F']))),
  AMBIGUOUS: merge(parse(text.eaw, new Set(['A']))),
  ZERO: merge([...parse(text.gc, new Set(['Mn', 'Me', 'Cf'])), [0x1160, 0x11ff], [0xd7b0, 0xd7ff]]),
  JOIN: merge(
    parse(
      text.gcb,
      new Set(['Extend', 'ZWJ', 'SpacingMark', 'Prepend', 'Regional_Indicator', 'L', 'V', 'T']),
    ),
  ),
};

for (const [name, t] of Object.entries(tables)) if (!t.length) fail(`${name} is empty`);
// emoji presentation is wide, regional indicators aside
for (const [a, b] of parse(text.emoji, new Set(['Emoji_Presentation']))) {
  for (let cp = a; cp <= b; cp++) {
    if ((cp < 0x1f1e6 || cp > 0x1f1ff) && !has(tables.WIDE, cp)) {
      fail(`U+${cp.toString(16).toUpperCase()} is Emoji_Presentation but not wide`);
    }
  }
}

const hex = (n) => `0x${n.toString(16)}`;
let src = `// Generated by scripts/gen-eaw.mjs from Unicode ${UNICODE} data. Do not edit.\n\n`;
src += `export const UNICODE_VERSION = '${UNICODE}';\n`;
for (const [name, t] of Object.entries(tables)) {
  src += `\nexport const ${name}: readonly number[] = [\n${t.map(([a, b]) => `  ${hex(a)}, ${hex(b)},\n`).join('')}];\n`;
}

const tmp = `${out}.tmp-${process.pid}`;
try {
  fs.writeFileSync(tmp, src);
  fs.renameSync(tmp, out);
} catch (e) {
  fs.rmSync(tmp, { force: true });
  fail(`cannot write ${path.relative(root, out)}: ${e.message}`);
}

const win = process.platform === 'win32';
const biome = path.join(root, 'node_modules', '.bin', win ? 'biome.cmd' : 'biome');
const fmt = spawnSync(biome, ['format', '--write', 'src/core/eaw-table.ts'], {
  cwd: root,
  stdio: ['ignore', 'ignore', 'inherit'],
  shell: win,
});
if (fmt.status !== 0) fail('biome format failed; run `npx biome format --write src/core/eaw-table.ts`');

console.log(
  `gen-eaw: Unicode ${UNICODE} -> src/core/eaw-table.ts (${Object.entries(tables)
    .map(([name, t]) => `${name} ${t.length}`)
    .join(', ')})`,
);
