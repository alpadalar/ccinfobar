const ALL_WIDGETS = EVERY_WIDGET.filter((w) => !w.hidden);

const root = process.argv[2] ?? process.cwd();

function optionText(o: OptionSpec): string {
  const def = typeof o.default === 'string' ? `\`"${o.default}"\`` : `\`${o.default}\``;
  const choices = o.choices ? ` (${o.choices.map((c) => `\`${c.value}\``).join(', ')})` : '';
  const when = o.showWhen
    ? ` (when \`${o.showWhen.key}\` is ${o.showWhen.values.map((v) => `\`${v}\``).join(' or ')})`
    : '';
  return `\`${o.key}\` ${o.kind}, default ${def}${choices}${when}`;
}

function selfHiding(): string {
  const list = ALL_WIDGETS.filter((w) => w.hideWhenEmpty).map((w) => `\`${w.type}\``);
  if (!list.length) return '';
  const verb = list.length === 1 ? 'hides itself' : 'hide themselves';
  return `${list.join(', ')} ${verb} when empty; set \`hideEmpty: false\` on it to show \`—\` instead.`;
}

function widgetsMarkdown(): string {
  const out: string[] = [
    '# Widgets',
    '',
    '> Generated by `npm run docs`. Do not edit by hand.',
    '',
    `ccinfobar ships ${ALL_WIDGETS.length} widgets. A widget without data shows its label and \`—\`; set \`hideEmpty: true\` on it to hide it instead (handy for a GSD line outside GSD projects). ${selfHiding()}`,
    '',
    'Common fields for every widget in `config.json`: `color`, `background`, `bold`, `dim`, `italic`, `label`, `raw` (value only, no label), `merge` (no separator after it), `hideEmpty` (hide instead of showing `—` when there is no data) and `options`.',
    '',
    '## Categories',
    '',
  ];
  for (const c of CATEGORIES) {
    const n = ALL_WIDGETS.filter((w) => w.category === c.id).length;
    if (n)
      out.push(
        `- [${c.name}](#${c.name
          .toLowerCase()
          .replace(/[^a-z0-9]+/g, '-')
          .replace(/-$/, '')}) (${n})`,
      );
  }
  for (const c of CATEGORIES) {
    const list = ALL_WIDGETS.filter((w) => w.category === c.id);
    if (!list.length) continue;
    out.push(
      '',
      `## ${c.name}`,
      '',
      '| Type | Description | Example | Options |',
      '| --- | --- | --- | --- |',
    );
    for (const w of list) {
      const opts = (w.options ?? []).map(optionText).join('<br>') || '';
      const sample = w.sample ? `\`${(w.label ?? '') + w.sample}\`` : '';
      out.push(
        `| \`${w.type}\` | ${w.description.replace(/\|/g, '\\|')} | ${sample.replace(/\|/g, '\\|')} | ${opts.replace(/\|/g, '\\|')} |`,
      );
    }
  }
  return `${out.join('\n')}\n`;
}

