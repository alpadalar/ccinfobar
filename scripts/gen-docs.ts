import fs from 'node:fs';
import path from 'node:path';
import { THEMES } from '../src/core/themes.js';
import type { OptionSpec } from '../src/core/types.js';
import { ALL_WIDGETS, CATEGORIES } from '../src/widgets/index.js';

const root = process.argv[2] ?? process.cwd();

function optionText(o: OptionSpec): string {
  const def = typeof o.default === 'string' ? `\`"${o.default}"\`` : `\`${o.default}\``;
  const choices = o.choices ? ` (${o.choices.map((c) => `\`${c.value}\``).join(', ')})` : '';
  return `\`${o.key}\` ${o.kind}, default ${def}${choices}`;
}

function widgetsMarkdown(): string {
  const out: string[] = [
    '# Widgets',
    '',
    '> Generated by `npm run docs`. Do not edit by hand.',
    '',
    `ccinfobar ships ${ALL_WIDGETS.length} widgets. Every widget hides itself when it has nothing to show, so a GSD line disappears outside GSD projects.`,
    '',
    'Common fields for every widget in `config.json`: `color`, `background`, `bold`, `dim`, `italic`, `label`, `raw` (value only, no label), `merge` (no separator after it) and `options`.',
    '',
    '## Categories',
    '',
  ];
  for (const c of CATEGORIES) {
    const n = ALL_WIDGETS.filter((w) => w.category === c.id).length;
    if (n)
      out.push(
        `- [${c.name}](#${c.name
          .toLowerCase()
          .replace(/[^a-z0-9]+/g, '-')
          .replace(/-$/, '')}) (${n})`,
      );
  }
  for (const c of CATEGORIES) {
    const list = ALL_WIDGETS.filter((w) => w.category === c.id);
    if (!list.length) continue;
    out.push(
      '',
      `## ${c.name}`,
      '',
      '| Type | Description | Example | Options |',
      '| --- | --- | --- | --- |',
    );
    for (const w of list) {
      const opts = (w.options ?? []).map(optionText).join('<br>') || '';
      const sample = w.sample ? `\`${(w.label ?? '') + w.sample}\`` : '';
      out.push(
        `| \`${w.type}\` | ${w.description.replace(/\|/g, '\\|')} | ${sample.replace(/\|/g, '\\|')} | ${opts.replace(/\|/g, '\\|')} |`,
      );
    }
  }
  return `${out.join('\n')}\n`;
}

function schema(): object {
  const color = {
    type: 'string',
    description: 'Named color (red, brightBlue...), ansi256:N, #rrggbb or default',
  };
  return {
    $schema: 'http://json-schema.org/draft-07/schema#',
    $id: 'https://raw.githubusercontent.com/alpadalar/ccinfobar/main/schema/config.schema.json',
    title: 'ccinfobar config',
    type: 'object',
    properties: {
      $schema: { type: 'string' },
      version: { const: 1 },
      lines: {
        type: 'array',
        description: 'Status lines, top to bottom',
        items: {
          type: 'array',
          items: {
            type: 'object',
            required: ['type'],
            properties: {
              id: { type: 'string' },
              type: { type: 'string', enum: ALL_WIDGETS.map((w) => w.type) },
              color,
              background: color,
              bold: { type: 'boolean' },
              dim: { type: 'boolean' },
              italic: { type: 'boolean' },
              label: { type: 'string', description: 'Replaces the default label' },
              raw: { type: 'boolean', description: 'Show only the value' },
              merge: { type: 'boolean', description: 'Join with the next widget without a separator' },
              options: { type: 'object', additionalProperties: { type: ['string', 'number', 'boolean'] } },
            },
          },
        },
      },
      separator: { type: 'string', default: ' │ ' },
      separatorColor: color,
      padding: { type: 'integer', minimum: 0, maximum: 4, default: 1 },
      colorLevel: { enum: ['auto', 0, 1, 2, 3], default: 'auto' },
      icons: { enum: ['nerd', 'emoji', 'text', 'none'], default: 'text' },
      maxWidth: { anyOf: [{ const: 'auto' }, { type: 'integer', minimum: 1 }], default: 'auto' },
      widthOffset: { type: 'integer', minimum: 0, default: 4 },
      savePayload: { type: 'boolean', default: true },
      powerline: {
        type: 'object',
        properties: {
          enabled: { type: 'boolean', default: false },
          separator: { type: 'string' },
          startCap: { type: 'string' },
          endCap: { type: 'string' },
          theme: { enum: Object.keys(THEMES), default: 'default' },
        },
      },
    },
  };
}

fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.mkdirSync(path.join(root, 'schema'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/WIDGETS.md'), widgetsMarkdown());
fs.writeFileSync(path.join(root, 'schema/config.schema.json'), `${JSON.stringify(schema(), null, 2)}\n`);
console.log(`wrote docs/WIDGETS.md and schema/config.schema.json (${ALL_WIDGETS.length} widgets)`);
